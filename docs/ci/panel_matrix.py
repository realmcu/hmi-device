#!/usr/bin/env python3
"""Build the honeygui sample once per 8773G QSPI panel from panel_registry/panels.json.

This is the CI build matrix companion of panel_registry.py:
  - panel_registry.py --check   catches registration drift (fast)
  - panel_matrix.py --all       catches compile/link failures (slow)

Example (from the west workspace root):
  python modules/device/output/display/registry/panel_registry.py --check
  python modules/device/docs/ci/panel_matrix.py --all --jobs 1

The script creates a temporary Kconfig fragment for each panel, selecting that
panel and disabling the other manifest panels, then runs west build.

CI must provide:
  ZEPHYR_TOOLCHAIN_VARIANT, ZEPHYR_SDK_INSTALL_DIR (or the usual west env)
  west on PATH.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

DEVICE_ROOT = Path(__file__).resolve().parents[2]
MODULE_ROOT = DEVICE_ROOT.parent
WORKSPACE = MODULE_ROOT.parent
MANIFEST = DEVICE_ROOT / "output" / "display" / "registry" / "panels.json"


def load_manifest() -> dict:
    with MANIFEST.open("r", encoding="utf-8") as f:
        return json.load(f)


def panel_ids(panels: list[dict], selected: list[str] | None) -> list[dict]:
    if not selected:
        return [p for p in panels if p.get("build", True)]
    wanted = set(selected)
    unknown = wanted - {p["id"] for p in panels}
    if unknown:
        raise SystemExit(f"unknown panel id(s): {', '.join(sorted(unknown))}")
    return [p for p in panels if p["id"] in wanted and p.get("build", True)]


def make_fragment(panels: list[dict], target: dict, path: Path) -> None:
    lines = [
        "# Auto-generated by panel_matrix.py; do not commit.",
        f"CONFIG_{target['config']}=y",
    ]
    for p in panels:
        if p["config"] != target["config"]:
            lines.append(f"CONFIG_{p['config']}=n")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def build_one(panel: dict, defaults: dict, args: argparse.Namespace) -> tuple[str, bool, str]:
    sample = WORKSPACE / defaults["sample"]
    build_root = sample / "build_ci"
    build_dir = build_root / panel["id"]
    log_path = build_root / f"{panel['id']}.log"
    fragment = build_dir / "panel_fragment"

    cmd = [
        "west",
        "build",
        "-b",
        args.board,
        "-p",
        "-d",
        str(build_dir),
        "--",
        "-DENABLE_GENERATE_VERSION=OFF",
        f"-DEXTRA_CONF_FILE={fragment}",
    ]

    if args.dry_run:
        return panel["id"], True, "DRY-RUN: " + " ".join(cmd)

    build_root.mkdir(parents=True, exist_ok=True)
    # The Realtek post-build step resolves mp.ini/VERSION as <build>/../mp.ini.
    # Nested CI build dirs therefore need these files one level above them.
    for name in ("mp.ini", "VERSION"):
        src = sample / name
        if src.exists():
            shutil.copyfile(src, build_root / name)
    if build_dir.exists() and not args.keep:
        shutil.rmtree(build_dir)
    build_dir.mkdir(parents=True, exist_ok=True)
    make_fragment(load_manifest()["panels"], panel, fragment)

    with log_path.open("w", encoding="utf-8", errors="replace") as log:
        log.write("$ " + " ".join(cmd) + "\n\n")
        log.flush()
        proc = subprocess.run(
            cmd,
            cwd=sample,
            stdout=log,
            stderr=subprocess.STDOUT,
            text=True,
            env=os.environ.copy(),
        )

    ok = proc.returncode == 0
    tail = ""
    try:
        lines = log_path.read_text(encoding="utf-8", errors="replace").splitlines()
        tail = "\n".join(lines[-30:])
    except OSError:
        pass

    if ok and not args.keep:
        shutil.rmtree(build_dir, ignore_errors=True)
    return panel["id"], ok, tail


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--all", action="store_true", help="build every panel")
    parser.add_argument("--panel", action="append", default=[], help="panel id (repeatable)")
    parser.add_argument("--board", default=None, help="override board")
    parser.add_argument("--jobs", type=int, default=1, help="parallel builds (default 1)")
    parser.add_argument("--dry-run", action="store_true", help="print commands only")
    parser.add_argument("--keep", action="store_true", help="keep build directories")
    args = parser.parse_args()

    data = load_manifest()
    defaults = data.get("defaults", {})
    panels = data["panels"]

    if args.board is None:
        args.board = defaults.get("board", "rtl87x3g_sample")

    selected = panel_ids(panels, args.panel or None)
    if not args.all and not args.panel:
        parser.error("use --all or --panel <id>")
    if not selected:
        print("no panels selected")
        return 0

    print(f"panel matrix: {len(selected)} panel(s), board={args.board}, jobs={args.jobs}")
    results = []
    if args.jobs <= 1:
        for panel in selected:
            pid, ok, detail = build_one(panel, defaults, args)
            results.append((pid, ok, detail))
            print(f"  {'PASS' if ok else 'FAIL'}  {pid}")
            if not ok and detail:
                print(detail)
    else:
        with ThreadPoolExecutor(max_workers=args.jobs) as pool:
            futures = {
                pool.submit(build_one, panel, defaults, args): panel["id"]
                for panel in selected
            }
            for fut in as_completed(futures):
                pid = futures[fut]
                try:
                    _, ok, detail = fut.result()
                except Exception as exc:  # noqa: BLE001 - report and continue
                    ok, detail = False, str(exc)
                results.append((pid, ok, detail))
                print(f"  {'PASS' if ok else 'FAIL'}  {pid}")
                if not ok and detail:
                    print(detail)

    failed = [pid for pid, ok, _ in results if not ok]
    print(f"\nsummary: {len(results) - len(failed)} passed, {len(failed)} failed")
    if failed:
        print("failed panels: " + ", ".join(sorted(failed)))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
