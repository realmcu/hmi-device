#!/usr/bin/env python3
"""Generate and validate 8773G SDI/RGB panel registration.

The manifest registry/panels.json is the single source of truth for:
  - registry/Kconfig.panels          (sourced by display/Kconfig)
  - registry/panel_registry.cmake    (included by CMake)
  - registry/panel_sources.py        (compatibility output)

Usage (from the west workspace root):
  python modules/device/registry/panel_registry.py --check
  python modules/device/registry/panel_registry.py --generate
  python modules/device/registry/panel_registry.py --list
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

DEVICE_ROOT = Path(__file__).resolve().parents[1]
MODULES_ROOT = DEVICE_ROOT.parent
WORKSPACE = MODULES_ROOT.parent
DISPLAY_ROOT = MODULES_ROOT / "display"
REGISTRY = DEVICE_ROOT / "registry"
MANIFEST = REGISTRY / "panels.json"
KCONFIG = DISPLAY_ROOT / "Kconfig"
GEN_KCONFIG = REGISTRY / "Kconfig.panels"
GEN_CMAKE = REGISTRY / "panel_registry.cmake"
GEN_PY = REGISTRY / "panel_sources.py"

CORE_CMAKE = DEVICE_ROOT / "core" / "CMakeLists.txt"
PANEL_CMAKE = DEVICE_ROOT / "panel" / "CMakeLists.txt"
GENERAL_CMAKE = DEVICE_ROOT / "legacy" / "CMakeLists.txt"
WRAPPER_CMAKE = DEVICE_ROOT / "zephyr" / "display" / "CMakeLists.txt"

VALID_INTERFACES = {"SDI", "RGB"}


def load_manifest() -> dict:
    with MANIFEST.open("r", encoding="utf-8") as f:
        data = json.load(f)

    panels = data.get("panels", [])
    if not panels:
        raise SystemExit("manifest has no panels")

    seen_config = set()
    seen_id = set()
    for p in panels:
        for key in ("id", "config", "name", "source", "migrated", "interface"):
            if key not in p:
                raise SystemExit(f"panel entry missing {key!r}: {p}")
        if p["interface"] not in VALID_INTERFACES:
            raise SystemExit(f"bad interface {p['interface']!r}: {p['id']}")
        if p["id"] in seen_id:
            raise SystemExit(f"duplicate id: {p['id']}")
        if p["config"] in seen_config:
            raise SystemExit(f"duplicate config: {p['config']}")
        seen_id.add(p["id"])
        seen_config.add(p["config"])
    return data


def panel_source(p: dict) -> str:
    return f'${{RTK_PANEL_DEVICE_ROOT}}/{p["source"]}'


def render_kconfig(panels: list[dict]) -> str:
    lines = [
        "# Auto-generated by registry/panel_registry.py from registry/panels.json.",
        "# Do not edit by hand.",
        "",
    ]
    for p in panels:
        lines += [
            f"config {p['config']}",
            f"\tbool \"{p.get('help', p['name'])}\"",
            "\tdefault n",
            "\thelp",
            f"\t\t{p['interface']} panel: {p['name']}.",
            "",
        ]
    return "\n".join(lines)


def render_cmake(panels: list[dict]) -> str:
    sdi = [p for p in panels if p["interface"] == "SDI"]
    rgb = [p for p in panels if p["interface"] == "RGB"]
    migrated = [p for p in panels if p["migrated"]]
    legacy = [p for p in panels if not p["migrated"]]

    lines = [
        "# Auto-generated by registry/panel_registry.py from registry/panels.json.",
        "# Do not edit by hand.",
        "",
        'get_filename_component(RTK_PANEL_DEVICE_ROOT "${CMAKE_CURRENT_LIST_DIR}/.." ABSOLUTE)',
        "",
        "set(RTK_8773G_PANEL_SOURCES",
    ]
    for p in panels:
        lines.append(f'    "CONFIG_{p["config"]}|{panel_source(p)}"')
    lines += [")", "", "set(RTK_8773G_SDI_PANEL_SOURCES"]
    for p in sdi:
        lines.append(f'    "CONFIG_{p["config"]}|{panel_source(p)}"')
    lines += [")", "", "set(RTK_8773G_RGB_PANEL_SOURCES"]
    for p in rgb:
        lines.append(f'    "CONFIG_{p["config"]}|{panel_source(p)}"')
    lines += [")", "", "set(RTK_8773G_PANEL_CONFIGS"]
    for p in panels:
        lines.append(f"    CONFIG_{p['config']}")
    lines += [")", "", "set(RTK_8773G_SDI_PANEL_CONFIGS"]
    for p in sdi:
        lines.append(f"    CONFIG_{p['config']}")
    lines += [")", "", "set(RTK_8773G_RGB_PANEL_CONFIGS"]
    for p in rgb:
        lines.append(f"    CONFIG_{p['config']}")
    lines += [
        ")",
        "",
        "set(RTK_8773G_SDI_SELECTED_COUNT 0)",
        "foreach(panel_config IN LISTS RTK_8773G_SDI_PANEL_CONFIGS)",
        "    if(${panel_config})",
        '        math(EXPR RTK_8773G_SDI_SELECTED_COUNT "${RTK_8773G_SDI_SELECTED_COUNT} + 1")',
        "    endif()",
        "endforeach()",
        "if(RTK_8773G_SDI_SELECTED_COUNT GREATER 1)",
        '    message(FATAL_ERROR "Select only one 8773G SDI panel")',
        "endif()",
        "if(RTK_8773G_SDI_SELECTED_COUNT EQUAL 1)",
        "    set(RTK_8773G_SDI_ENABLED ON)",
        "else()",
        "    set(RTK_8773G_SDI_ENABLED OFF)",
        "endif()",
        "",
        "set(RTK_8773G_RGB_SELECTED_COUNT 0)",
        "foreach(panel_config IN LISTS RTK_8773G_RGB_PANEL_CONFIGS)",
        "    if(${panel_config})",
        '        math(EXPR RTK_8773G_RGB_SELECTED_COUNT "${RTK_8773G_RGB_SELECTED_COUNT} + 1")',
        "    endif()",
        "endforeach()",
        "if(RTK_8773G_RGB_SELECTED_COUNT GREATER 1)",
        '    message(FATAL_ERROR "Select only one 8773G RGB panel")',
        "endif()",
        "if(RTK_8773G_RGB_SELECTED_COUNT EQUAL 1)",
        "    set(RTK_8773G_RGB_ENABLED ON)",
        "else()",
        "    set(RTK_8773G_RGB_ENABLED OFF)",
        "endif()",
        "",
        "set(RTK_8773G_MIGRATED_ENABLED OFF)",
    ]
    for p in migrated:
        lines += [
            f"if(CONFIG_{p['config']})",
            "    set(RTK_8773G_MIGRATED_ENABLED ON)",
            "endif()",
        ]
    lines += [
        "",
        "set(RTK_8773G_LEGACY_PANEL_SOURCES",
    ]
    for p in legacy:
        lines.append(f'    "CONFIG_{p["config"]}|{panel_source(p)}"')
    lines += [")", ""]
    return "\n".join(lines)


def render_python(panels: list[dict]) -> str:
    lines = [
        '"""Auto-generated by registry/panel_registry.py from registry/panels.json."""',
        "",
        "PANELS = [",
    ]
    for p in panels:
        lines += [
            "    {",
            f'        "id": "{p["id"]}",',
            f'        "config": "{p["config"]}",',
            f'        "interface": "{p["interface"]}",',
            f'        "chip": "{p.get("chip", "8773G")}",',
            f'        "migrated": {str(bool(p["migrated"]))},',
            f'        "source": "{p["source"]}",',
            "    },",
        ]
    lines += ["]", ""]
    return "\n".join(lines)


def write_if_changed(path: Path, content: str) -> bool:
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def generate(panels: list[dict]) -> None:
    changed = []
    if write_if_changed(GEN_KCONFIG, render_kconfig(panels)):
        changed.append(GEN_KCONFIG)
    if write_if_changed(GEN_CMAKE, render_cmake(panels)):
        changed.append(GEN_CMAKE)
    if write_if_changed(GEN_PY, render_python(panels)):
        changed.append(GEN_PY)

    if changed:
        for path in changed:
            print(f"generated: {path.relative_to(WORKSPACE)}")
    else:
        print("generated files already up to date")


def check_generated(panels: list[dict]) -> list[str]:
    errors = []
    expected = {
        GEN_KCONFIG: render_kconfig(panels),
        GEN_CMAKE: render_cmake(panels),
        GEN_PY: render_python(panels),
    }
    for path, content in expected.items():
        if not path.exists():
            errors.append(f"missing generated file: {path.relative_to(WORKSPACE)}")
        elif path.read_text(encoding="utf-8") != content:
            errors.append(
                f"stale generated file: {path.relative_to(WORKSPACE)} (run --generate)"
            )
    return errors


def check_kconfig(panels: list[dict]) -> list[str]:
    errors = []
    kconfig = KCONFIG.read_text(encoding="utf-8")
    if not re.search(r'^\s*(?:rsource|orsource)\s+"\.\./device/registry/Kconfig\.panels"\s*$',
                     kconfig, re.M):
        errors.append('Kconfig must source "../device/registry/Kconfig.panels"')

    gen = GEN_KCONFIG.read_text(encoding="utf-8") if GEN_KCONFIG.exists() else ""
    for p in panels:
        count = len(re.findall(rf"^config\s+{re.escape(p['config'])}\s*$", gen, re.M))
        if count != 1:
            errors.append(
                f"Kconfig.panels: {p['config']} defined {count} times (expected 1)"
            )
    return errors


def check_registration(panels: list[dict]) -> list[str]:
    errors = []
    panel_cmake = PANEL_CMAKE.read_text(encoding="utf-8")
    general = GENERAL_CMAKE.read_text(encoding="utf-8")
    wrapper = WRAPPER_CMAKE.read_text(encoding="utf-8")

    if "RTK_8773G_PANEL_SOURCES" not in panel_cmake:
        errors.append("device/panel/CMakeLists.txt does not use RTK_8773G_PANEL_SOURCES")

    if "panel_registry.cmake" not in wrapper:
        errors.append("Zephyr 8773G LCD CMakeLists.txt does not include panel_registry.cmake")
    if "RTK_8773G_SDI_ENABLED" not in wrapper and "RTK_LCD_8773G_QSPI_ENABLED" not in wrapper:
        errors.append("Zephyr 8773G LCD CMakeLists.txt does not use SDI enabled flag")

    for p in panels:
        source = DEVICE_ROOT / p["source"]
        if not source.exists():
            errors.append(f"source missing: {p['source']}")

        if p["migrated"]:
            if f'CONFIG_{p["config"]}' not in GEN_CMAKE.read_text(encoding="utf-8"):
                errors.append(f"migrated panel not registered: {p['config']}")
        else:
            pair = f'"CONFIG_{p["config"]}|{p.get("chip", "8773G")}"'
            if pair not in general:
                errors.append(f"legacy/CMakeLists.txt missing mapping: {pair}")
    return errors


def unregistered_kconfig_symbols(panels: list[dict]) -> list[str]:
    known = {p["config"] for p in panels}
    text = KCONFIG.read_text(encoding="utf-8")
    text += "\n" + (GEN_KCONFIG.read_text(encoding="utf-8") if GEN_KCONFIG.exists() else "")
    symbols = re.findall(
        r"^config\s+((?:REALTEK_LCD|REALTEK_SH8601Z)\w*)\s*$", text, re.M
    )
    ignored = {
        "REALTEK_DISPLAY_USE_PANEL_MANIFEST",
        "REALTEK_LCD_MAX_WIDTH",
        "REALTEK_LCD_SECTION_HEIGHT",
        "REALTEK_LCD_MAX_BYTES_PER_PIXEL",
        "REALTEK_LCD_FULL_FB_SIZE",
        "REALTEK_LCD_DC_DOUBLE",
    }
    return sorted(set(s for s in symbols if s not in known and s not in ignored))


def cmd_check(panels: list[dict], strict: bool) -> int:
    errors = []
    errors += check_generated(panels)
    errors += check_kconfig(panels)
    errors += check_registration(panels)

    warnings = unregistered_kconfig_symbols(panels)
    if warnings:
        print("warning: Kconfig symbols not in panels.json (legacy/out of Phase 1):")
        for sym in warnings:
            print(f"  {sym}")
        if strict:
            errors.append(f"{len(warnings)} Kconfig panel symbols are not in the manifest")

    if errors:
        print("panel registry check FAILED:")
        for err in errors:
            print(f"  - {err}")
        return 1

    print(f"panel registry check OK ({len(panels)} panels)")
    return 0


def cmd_list(panels: list[dict]) -> int:
    for p in panels:
        kind = "new" if p["migrated"] else "legacy"
        print(f"{p['id']:<28} {p['interface']:<4} {kind:<6} {p['config']}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check", action="store_true", help="validate registration")
    group.add_argument("--generate", action="store_true", help="regenerate files")
    group.add_argument("--list", action="store_true", help="list panels")
    parser.add_argument(
        "--strict",
        action="store_true",
        help="fail if Kconfig has panel symbols not present in the manifest",
    )
    args = parser.parse_args()

    data = load_manifest()
    panels = data["panels"]

    if args.generate:
        generate(panels)
        return 0
    if args.list:
        return cmd_list(panels)
    return cmd_check(panels, args.strict)


if __name__ == "__main__":
    sys.exit(main())